"""Build js/dtc-data.js (fault code -> description) from Mercedes CBF files.
Usage: python3 tools/cbf_dtcs.py OUT.js RESPID=FILE.cbf [RESPID=FILE.cbf ...]"""
import sys, os, json, re
sys.path.insert(0, os.path.dirname(__file__))
from cbf import load, S

out = {}
for arg in sys.argv[2:]:
    rid, path = arg.split('=', 1)
    strings, ecus = load(path)
    m = {}
    for q, d, _ in ecus[0].dtcs:
        if not q: continue
        desc = re.sub(r'\s+', ' ', S(strings, d)).strip()
        # MED descriptions often repeat "<text> <failure type>"; keep it short
        m[q.upper()] = desc[:140]
    out[rid.upper()] = m
with open(sys.argv[1], 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/cbf_dtcs.py from the Mercedes CBF files. Do not edit.\n')
    f.write('export const DTC_TEXT = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print({k: len(v) for k, v in out.items()})
