"""Generate firmware/src/fonts.h (4-bit anti-aliased bitmap fonts) and firmware/src/dtc_text.h
(fault code descriptions, from ../js/dtc-data.js). Run from the repo root:
    python3 firmware/tools/gen_assets.py"""
import json, os, re
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'firmware', 'src')
BOLD = '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf'
REG = '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'

ASCII = ''.join(chr(c) for c in range(32, 127)) + '°'
FONTS = [
    # name, ttf, pixel size, charset
    ('F_SMALL', REG, 14, ASCII),
    ('F_LABEL', BOLD, 13, ASCII),
    ('F_MED', BOLD, 34, '0123456789-.+ °CFpsigalbarVkPhm%/?'),
    ('F_BIG', BOLD, 64, '0123456789-. '),
    ('F_GEAR', BOLD, 112, 'PRNDM-?123456789 '),
]

def gen_font(name, ttf, size, chars):
    f = ImageFont.truetype(ttf, size)
    asc, desc = f.getmetrics()
    data = bytearray(); glyphs = []
    for ch in chars:
        l, t, r, b = f.getbbox(ch, anchor='ls')
        w, h = max(0, r - l), max(0, b - t)
        adv = round(f.getlength(ch))
        off = len(data)
        if w and h:
            im = Image.new('L', (w, h), 0)
            ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255, anchor='ls')
            px = list(im.tobytes())
            nib = [p >> 4 for p in px]
            if len(nib) % 2: nib.append(0)
            for i in range(0, len(nib), 2): data.append((nib[i] << 4) | nib[i + 1])
        glyphs.append((ord(ch), off, w, h, l, t, adv))
    lines = [f'static const uint8_t {name}_bmp[] PROGMEM = {{']
    for i in range(0, len(data), 24):
        lines.append('  ' + ','.join(str(b) for b in data[i:i + 24]) + ',')
    lines.append('};')
    lines.append(f'static const Glyph {name}_glyphs[] = {{')
    for g in glyphs:
        lines.append('  {%d,%d,%d,%d,%d,%d,%d},' % g)
    lines.append('};')
    lines.append(f'static const Font {name} = {{ {name}_glyphs, {len(glyphs)}, {name}_bmp, {asc}, {desc} }};')
    return '\n'.join(lines), len(data)

def main():
    parts = ['// Generated by firmware/tools/gen_assets.py (DejaVu Sans, Bitstream Vera license). Do not edit.',
             '#pragma once', '#include <stdint.h>', '#include <pgmspace.h>',
             'struct Glyph { uint16_t cp; uint32_t off; uint8_t w, h; int8_t xo, yo; uint8_t adv; };',
             'struct Font { const Glyph *glyphs; uint16_t count; const uint8_t *bmp; uint8_t ascent, descent; };']
    total = 0
    for spec in FONTS:
        src, n = gen_font(*spec); parts.append(src); total += n
    open(os.path.join(OUT, 'fonts.h'), 'w').write('\n'.join(parts) + '\n')
    print('fonts bytes', total)

    js = open(os.path.join(ROOT, 'js', 'dtc-data.js'), encoding='utf-8').read()
    m = json.loads(js[js.index('{'):js.rindex('}') + 1])
    def cstr(s):
        s = re.sub(r'\s*no sub type information$', '', s, flags=re.I)
        s = s.encode('ascii', 'replace').decode().replace('\\', '/').replace('"', "'")
        return s[:90]
    out = ['// Generated by firmware/tools/gen_assets.py from js/dtc-data.js. Do not edit.', '#pragma once',
           'struct DtcText { const char *code; const char *text; };']
    for rid, table in m.items():
        items = sorted(table.items())
        out.append(f'static const DtcText DTC_{rid}[] = {{')
        out += [f'  {{"{k}","{cstr(v)}"}},' for k, v in items]
        out.append('};')
        out.append(f'static const uint16_t DTC_{rid}_N = {len(items)};')
    open(os.path.join(OUT, 'dtc_text.h'), 'w', encoding='ascii').write('\n'.join(out) + '\n')
    print('dtc', {k: len(v) for k, v in m.items()})

main()
